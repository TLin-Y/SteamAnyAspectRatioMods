void Adopt(IUnknown* dev, IDXGISwapChain* sc) {
    ID3D12CommandQueue* q = nullptr;
    if (!dev || FAILED(dev->QueryInterface(__uuidof(ID3D12CommandQueue), (void**)&q))) return;
    if (queue) queue->Release();
    queue = q;
    swapChain = sc;
    if (hkPresent) return;
    hkPresent = safetyhook::create_inline(VFunc(sc, 8), &Present);
    hkResizeBuffers = safetyhook::create_inline(VFunc(sc, 13), &ResizeBuffers);
    IDXGISwapChain3* sc3 = nullptr;
    if (SUCCEEDED(sc->QueryInterface(__uuidof(IDXGISwapChain3), (void**)&sc3))) {
        hkPresent1 = safetyhook::create_inline(VFunc(sc3, 22), &Present1);
        hkResizeBuffers1 = safetyhook::create_inline(VFunc(sc3, 39), &ResizeBuffers1);
        sc3->Release();
    }
    SPDLOG_INFO("Stretch hooks installed (DX12).");
}

