    Section CodeSection()
    {
        auto base = reinterpret_cast<uint8_t*>(exeModule);
        auto dos = reinterpret_cast<IMAGE_DOS_HEADER*>(base);
        auto nt = reinterpret_cast<IMAGE_NT_HEADERS*>(base + dos->e_lfanew);
        auto sec = IMAGE_FIRST_SECTION(nt);
        Section best{};
        for (WORD i = 0; i < nt->FileHeader.NumberOfSections; ++i, ++sec) {
            if (!(sec->Characteristics & IMAGE_SCN_MEM_EXECUTE)) continue;
            if (!best.start || std::memcmp(sec->Name, ".xcode", 6) == 0 || std::memcmp(sec->Name, ".text", 5) == 0) {
                best = { base + sec->VirtualAddress, sec->Misc.VirtualSize };
                if (std::memcmp(sec->Name, ".xcode", 6) == 0) break;
            }
        }
        return best;
    }

    std::vector<int> Parse(const char* pattern)
    {
        std::vector<int> bytes;
        for (const char* p = pattern; *p;) {
            if (*p == ' ') { ++p; continue; }
            if (*p == '?') { bytes.push_back(-1); while (*p == '?') ++p; continue; }
            char* end = nullptr;
            bytes.push_back(static_cast<int>(strtoul(p, &end, 16)));
            p = end;
        }
        return bytes;
    }

    size_t ScanRaw(const uint8_t* start, size_t size, const int* bytes, size_t n, uint8_t** out, size_t max)
    {
        size_t found = 0;
        __try {
            for (size_t i = 0; i + n <= size; ++i) {
                if (bytes[0] >= 0 && start[i] != bytes[0]) continue;
                bool ok = true;
                for (size_t k = 1; k < n; ++k) {
                    if (bytes[k] >= 0 && start[i + k] != bytes[k]) { ok = false; break; }
                }
                if (ok && found < max) out[found++] = const_cast<uint8_t*>(start + i);
            }
        } __except (EXCEPTION_EXECUTE_HANDLER) {
            return 0;
        }
        return found;
    }

    std::vector<uint8_t*> Scan(const char* pattern)
    {
        auto bytes = Parse(pattern);
        auto s = CodeSection();
        if (!s.start || s.size < bytes.size()) return {};
        uint8_t* out[16] = {};
        size_t n = ScanRaw(s.start, s.size, bytes.data(), bytes.size(), out, 16);
        return std::vector<uint8_t*>(out, out + n);
    }

    std::vector<uint8_t*> ScanCount(const std::string& name, const char* pattern, size_t count)
    {
        auto hits = Scan(pattern);
        if (hits.size() != count) {
            spdlog::error("{}: expected {} match(es), found {}", name, count, hits.size());
            return {};
        }
        for (auto h : hits) spdlog::info("{}: {:X}", name, reinterpret_cast<uintptr_t>(h));
        return hits;
    }

