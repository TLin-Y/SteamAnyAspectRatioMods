    float ScreenAspect()
    {
        if (!pRenderSize || pRenderSize[0] <= 0 || pRenderSize[1] <= 0) return kAspect;
        return static_cast<float>(pRenderSize[0]) / static_cast<float>(pRenderSize[1]);
    }

    bool IsDefaultAspect(float aspect)
    {
        return std::fabs(aspect - kAspect) < 0.01f;
    }

    void Correct(float& m00, float& m11, float aspect)
    {
        if (!IsDefaultAspect(aspect)) return;
        float r = ScreenAspect() / kAspect;
        if (r < 0.999f) m11 *= r;
        else if (r > 1.001f) m00 /= r;
        m00 /= fFov;
        m11 /= fFov;
    }

    void CorrectStored(uint8_t* cam)
    {
        auto m00 = reinterpret_cast<float*>(cam + 0x60);
        auto m11 = reinterpret_cast<float*>(cam + 0x74);
        Correct(*m00, *m11, *reinterpret_cast<float*>(cam + 0x1AC));
    }

