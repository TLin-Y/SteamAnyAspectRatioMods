"""Write THIRD_PARTY_LICENSES.txt: the license texts of the npm packages bundled into dist/index.js.

Usage (from AnyAspectRatioDecky, after pnpm install):
    pnpm licenses list --prod --json | python scripts/third_party_licenses.py

Type-only packages (@types/*) are not part of the bundle and are skipped. Run it again whenever
package.json or pnpm-lock.yaml changes, and commit the result.
"""

import json
import sys
from pathlib import Path

PLUGIN_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = PLUGIN_ROOT / "THIRD_PARTY_LICENSES.txt"
LICENSE_NAMES = ("license", "license.md", "license.txt", "licence", "licence.md", "copying")


def license_text(package_dir: Path) -> str | None:
    files = {path.name.lower(): path for path in package_dir.iterdir() if path.is_file()}
    for name in LICENSE_NAMES:
        if name in files:
            return files[name].read_text(encoding="utf-8", errors="replace").strip()
    return None


def render(packages: list[dict]) -> str:
    sections = [
        "Third-party software bundled in dist/index.js",
        "=" * 46,
        "",
        "Generated by scripts/third_party_licenses.py from the production dependencies in pnpm-lock.yaml.",
    ]
    for package in sorted(packages, key=lambda item: item["name"]):
        if package["name"].startswith("@types/"):
            continue
        for version, path in zip(package["versions"], package["paths"]):
            text = license_text(Path(path))
            sections += [
                "",
                "-" * 79,
                f"{package['name']} {version} ({package['license']})",
                package.get("homepage") or "",
                "",
                text or f"No license file is shipped in the package; its package.json declares {package['license']}.",
            ]
    return "\n".join(sections).rstrip() + "\n"


def main() -> None:
    by_license = json.loads(sys.stdin.buffer.read().decode("utf-8-sig"))
    packages = [package for group in by_license.values() for package in group]
    OUTPUT.write_bytes(render(packages).replace("\n", "\r\n").encode("utf-8"))
    print(f"Wrote {OUTPUT.name} ({sum(not p['name'].startswith('@types/') for p in packages)} packages)")


if __name__ == "__main__":
    main()
